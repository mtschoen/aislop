let temporaryDirectory: string;

const makeContext = (files: string[], repeatedLiteralThreshold?: number): EngineContext => ({
	rootDirectory: temporaryDirectory,
	languages: ["python"],
	frameworks: ["none"],
	files,
	installedTools: {},
	config: {
		quality: {
			maxFunctionLoc: 80,
			maxFileLoc: 400,
			maxNesting: 5,
			maxParams: 6,
			...(repeatedLiteralThreshold === undefined ? {} : { repeatedLiteralThreshold }),
		},
		security: { audit: true, auditTimeout: 25000 },
	},
});

const writeFile = (filename: string, content: string): string => {
	const filePath = path.join(temporaryDirectory, filename);
	fs.mkdirSync(path.dirname(filePath), { recursive: true });
	fs.writeFileSync(filePath, content, "utf-8");
	return filePath;
};

const repeatedPythonCalls = (name: string, value: string, count: number): string[] =>
	Array.from(
		{ length: count },
		(_element, index) => `responses.append(requests.get(urls[${index}], ${name}=${value}))`,
	);

const repeatedLiteralMatches = (
	diagnostics: Awaited<ReturnType<typeof detectHardcodedConfigLiterals>>,
) => diagnostics.filter((diagnostic) => diagnostic.rule === "ai-slop/repeated-magic-literal");

beforeEach(() => {
	temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "aislop-repeated-literals-"));
});

afterEach(() => {
	fs.rmSync(temporaryDirectory, { recursive: true, force: true });
});

