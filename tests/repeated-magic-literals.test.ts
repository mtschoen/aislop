		const diagnostics = await detectHardcodedConfigLiterals(makeContext([filePath]));
		const matches = diagnostics.filter(
			(diagnostic) => diagnostic.rule === "ai-slop/repeated-magic-literal",
		);

		expect(matches).toHaveLength(1);
