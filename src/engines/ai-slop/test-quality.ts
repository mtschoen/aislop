import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
import { relativePosix } from "../../utils/paths.js";
import { getTestFiles, isAutoGenerated } from "../../utils/source-files.js";
import { maskStringsAndComments } from "../../utils/source-masker.js";
import type { Diagnostic, EngineContext } from "../types.js";

import { parseJavaScriptTest, suppressionPosition } from "./test-javascript-ast.js";

const JS_EXTENSIONS = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"]);

const EXPECT_NAME = "ex" + "pect";
const ASSERT_NAME = "as" + "sert";
const TRUE_NAME = "tr" + "ue";
const PYTHON_TAUTOLOGY_RES = [
	new RegExp(String.raw`^\s*${ASSERT_NAME}\s+(?:True|1)\s*(?:,.*)?$`),
	new RegExp(String.raw`^\s*self\s*\.\s*${ASSERT_NAME}True\s*\(\s*True\s*[,)]`),
];
const CSHARP_TAUTOLOGY_RE = new RegExp(
	String.raw`(?<![\p{ID_Continue}])As${"sert"}\s*\.\s*(?:True|IsTrue)\s*\(\s*${TRUE_NAME}\s*[,)]`,
	"u",
);

type FixedLiteral = string | number | boolean | null | undefined;

const fixedLiteral = (expression: ts.Expression): { value: FixedLiteral } | null => {
	switch (expression.kind) {
		case ts.SyntaxKind.TrueKeyword:
			return { value: true };
		case ts.SyntaxKind.FalseKeyword:
			return { value: false };
		case ts.SyntaxKind.NullKeyword:
			return { value: null };
	}
	if (ts.isIdentifier(expression) && expression.text === "unde" + "fined")
		return { value: undefined };
	if (ts.isNumericLiteral(expression)) return { value: Number(expression.text) };
	if (ts.isStringLiteral(expression) || ts.isNoSubstitutionTemplateLiteral(expression))
		return { value: expression.text };
	if (
		ts.isPrefixUnaryExpression(expression) &&
		expression.operator === ts.SyntaxKind.MinusToken &&
		ts.isNumericLiteral(expression.operand)
	) {
		return { value: -Number(expression.operand.text) };
	}
	return null;
};

const literalsAreEqual = (left: ts.Expression, right: ts.Expression): boolean => {
	const leftLiteral = fixedLiteral(left);
	const rightLiteral = fixedLiteral(right);
	return (
		leftLiteral !== null &&
		rightLiteral !== null &&
		Object.is(leftLiteral.value, rightLiteral.value)
	);
};

const isNamedIdentifier = (expression: ts.Expression, name: string): boolean =>
	ts.isIdentifier(expression) && expression.text === name;

// Closed question: is this exact assertion call over equal fixed literals, or
// one of the enumerated assertions over the true keyword? No bindings inferred.
const isTautologicalCall = (call: ts.CallExpression): boolean => {
	const target = call.expression;
	if (isNamedIdentifier(target, ASSERT_NAME))
		return call.arguments[0]?.kind === ts.SyntaxKind.TrueKeyword;
	if (!ts.isPropertyAccessExpression(target)) return false;
	if (isNamedIdentifier(target.expression, ASSERT_NAME)) {
		if (target.name.text === "o" + "k")
			return call.arguments[0]?.kind === ts.SyntaxKind.TrueKeyword;
		return (
			["eq" + "ual", "strict" + "Equal"].includes(target.name.text) &&
			call.arguments.length >= 2 &&
			literalsAreEqual(call.arguments[0], call.arguments[1])
		);
	}
	const inner = target.expression;
	if (
		!ts.isCallExpression(inner) ||
		!isNamedIdentifier(inner.expression, EXPECT_NAME) ||
		inner.arguments.length !== 1
	)
		return false;
	if (target.name.text === "to" + "Be")
		return call.arguments.length === 1 && literalsAreEqual(inner.arguments[0], call.arguments[0]);
	return (
		target.name.text === "toBe" + "Truthy" &&
		call.arguments.length === 0 &&
		inner.arguments[0].kind === ts.SyntaxKind.TrueKeyword
	);
};

const tautologicalPositions = (
	content: string,
	filePath: string,
	extension: string,
): Array<{ line: number; column: number }> => {
	const positions: Array<{ line: number; column: number }> = [];
	if (JS_EXTENSIONS.has(extension)) {
		const sourceFile = parseJavaScriptTest(filePath, content, extension);
		const visit = (node: ts.Node): void => {
			if (ts.isCallExpression(node) && isTautologicalCall(node)) {
				const position = suppressionPosition(sourceFile, node.getStart(sourceFile));
				positions.push({ line: position.line + 1, column: position.character + 1 });
			}
			ts.forEachChild(node, visit);
		};
		visit(sourceFile);
	} else {
		const lines = maskStringsAndComments(content, extension).split("\n");
		for (let index = 0; index < lines.length; index++) {
			if (
				extension === ".py"
					? PYTHON_TAUTOLOGY_RES.some((pattern) => pattern.test(lines[index]))
					: extension === ".cs" && CSHARP_TAUTOLOGY_RE.test(lines[index])
			)
				positions.push({ line: index + 1, column: 1 });
		}
	}
	return positions;
};

export const detectTautologicalTests = async (context: EngineContext): Promise<Diagnostic[]> => {
	const diagnostics: Diagnostic[] = [];
	for (const filePath of getTestFiles(context)) {
		if (isAutoGenerated(filePath)) continue;
		let content: string;
		try {
			content = fs.readFileSync(filePath, "utf-8");
		} catch {
			continue;
		}

		const extension = path.extname(filePath).toLowerCase();
		for (const position of tautologicalPositions(content, filePath, extension)) {
			diagnostics.push({
				filePath: relativePosix(context.rootDirectory, filePath),
				engine: "ai-slop",
				rule: "ai-slop/tautological-test",
				severity: "warning",
				message: "Tautological test assertion cannot fail",
				help: "Assert behavior produced by the code under test instead of comparing fixed literals.",
				line: position.line,
				column: position.column,
				category: "AI Slop",
				fixable: false,
			});
		}
	}
	return diagnostics;
};
