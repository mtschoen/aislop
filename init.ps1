<#
.SYNOPSIS
Restores this checkout after `git clean -ffxd`.

.DESCRIPTION
Restores packages and the agent instruction files generated by aislop. Reports
prerequisites instead of installing them. Every step is idempotent.

.PARAMETER Build
Also run `pnpm build` after restoring packages.
#>
[CmdletBinding()]
param(
    [switch]$Build
)

$ErrorActionPreference = 'Stop'
$repositoryRoot = $PSScriptRoot
Set-Location $repositoryRoot
$missingPrerequisites = [System.Collections.Generic.List[string]]::new()
$completedSteps = [System.Collections.Generic.List[string]]::new()

function Test-CommandAvailable {
    param([Parameter(Mandatory)][string]$Name)
    return $null -ne (Get-Command $Name -ErrorAction SilentlyContinue)
}

function Test-AislopRunnable {
    if (-not (Test-CommandAvailable 'aislop')) { return $false }
    $previousPreference = $ErrorActionPreference
    $ErrorActionPreference = 'SilentlyContinue'
    try {
        & aislop --version 2>$null | Out-Null
        return $LASTEXITCODE -eq 0
    }
    finally {
        $ErrorActionPreference = $previousPreference
    }
}

Write-Host 'Checking prerequisites...'
if (Test-CommandAvailable 'node') {
    $nodeVersion = (& node --version 2>$null)
    Write-Host "  Node.js             $nodeVersion"
}
else {
    $missingPrerequisites.Add('Node.js ^22.18 || >=24.11 - https://nodejs.org')
    Write-Host '  Node.js             MISSING' -ForegroundColor Red
}

if (Test-CommandAvailable 'pnpm') {
    $pnpmVersion = (& pnpm --version 2>$null)
    Write-Host "  pnpm                $pnpmVersion"
}
else {
    $missingPrerequisites.Add('pnpm - enable Corepack or see https://pnpm.io/installation')
    Write-Host '  pnpm                MISSING' -ForegroundColor Red
}

$aislopOnPath = Test-CommandAvailable 'aislop'
if ($aislopOnPath) {
    if (Test-AislopRunnable) {
        $aislopVersion = (& aislop --version 2>$null)
        Write-Host "  aislop              $aislopVersion"
    }
    else {
        Write-Host '  aislop              on PATH, not runnable yet (agent files only)' -ForegroundColor Yellow
    }
}
else {
    Write-Host '  aislop              missing (agent files only)' -ForegroundColor Yellow
}

if (-not (Test-CommandAvailable 'node') -or -not (Test-CommandAvailable 'pnpm')) {
    Write-Host 'Cannot restore packages without Node.js and pnpm.' -ForegroundColor Red
    foreach ($prerequisite in $missingPrerequisites) {
        Write-Host "  - $prerequisite"
    }
    exit 1
}

Write-Host ''
Write-Host 'Restoring packages...'
& pnpm install --frozen-lockfile --ignore-scripts
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
$completedSteps.Add('Packages restored')

# Build before the agent instruction files: the documented fleet installation
# runs `aislop` through scripts/wrappers/aislop.cmd, which needs this checkout's
# dist/cli.js. Building last left the wrapper unusable at the hook step, so the
# restore failed before the build that would have fixed it.
if ($Build) {
    Write-Host ''
    Write-Host 'Building aislop...'
    & pnpm build
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
    $completedSteps.Add('Build output restored')
}

if (Test-AislopRunnable) {
    Write-Host ''
    Write-Host 'Restoring agent instruction files...'
    & aislop hook install claude --project
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
    $completedSteps.Add('.claude/AISLOP.md and .claude/CLAUDE.md restored')

    if (Test-CommandAvailable 'git') {
        $settingsPath = '.claude/settings.json'
        & git -C $repositoryRoot diff --quiet -- $settingsPath
        $ordinaryContentChange = $LASTEXITCODE -ne 0
        & git -C $repositoryRoot diff --cached --quiet -- $settingsPath
        $stagedContentChange = $LASTEXITCODE -ne 0
        $status = & git -C $repositoryRoot status --porcelain -- $settingsPath
        if (-not $ordinaryContentChange -and -not $stagedContentChange -and $status) {
            & git -C $repositoryRoot restore --worktree --source=HEAD -- $settingsPath
            if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
            Write-Host 'Normalized line endings in .claude/settings.json.'
        }
    }
}
elseif ($aislopOnPath) {
    Write-Host ''
    Write-Host 'Skipping agent instruction files: aislop is on PATH but not runnable.' -ForegroundColor Yellow
    Write-Host 'Build it (.\init.ps1 -Build), then run: aislop hook install claude --project'
    $missingPrerequisites.Add('aislop (agent files only) - on PATH but not runnable')
}
else {
    Write-Host ''
    Write-Host 'Skipping agent instruction files: aislop is not installed.' -ForegroundColor Yellow
    Write-Host 'Once installed, run: aislop hook install claude --project'
    $missingPrerequisites.Add('aislop (agent files only) - see docs/installation.md')
}

$provisioner = @('schoen-lab-onboard', 'schoen-lab') |
    Where-Object { Test-CommandAvailable $_ } |
    Select-Object -First 1
if ($provisioner) {
    Write-Host ''
    Write-Host 'Re-applying provisioned project settings...'
    & $provisioner apply auto-memory
    if ($LASTEXITCODE -eq 0) {
        $completedSteps.Add('Project-scope provisioned settings re-applied')
    }
    else {
        Write-Host "$provisioner apply auto-memory failed; continuing." -ForegroundColor Yellow
    }
}

Write-Host ''
Write-Host 'Done.' -ForegroundColor Green
foreach ($step in $completedSteps) { Write-Host "  $step" }
if ($missingPrerequisites.Count -gt 0) {
    Write-Host ''
    Write-Host 'Missing prerequisites (install manually):' -ForegroundColor Yellow
    foreach ($prerequisite in $missingPrerequisites) {
        Write-Host "  - $prerequisite"
    }
}
if (-not $Build) {
    Write-Host ''
    Write-Host 'Next: .\init.ps1 -Build (.\init.bat -Build from cmd.exe), or pnpm test.'
}
exit 0
